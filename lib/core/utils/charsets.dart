import 'dart:convert';

/// Decodes feed and page bytes using the charset the server or the document
/// declares: UTF-8 (the default), Latin-1 / Windows-1252, or Windows-1256 /
/// ISO-8859-6, which some Arabic news sites still use.
String decodeTextBody(List<int> bytes, {String? contentType}) {
  final head = latin1
      .decode(bytes.take(1024).toList(), allowInvalid: true)
      .toLowerCase();
  final charset =
      _charsetParam.firstMatch((contentType ?? '').toLowerCase())?.group(1) ??
      _xmlEncoding.firstMatch(head)?.group(1) ??
      _charsetParam.firstMatch(head)?.group(1) ??
      'utf-8';
  return switch (charset) {
    'windows-1256' || 'cp1256' => String.fromCharCodes([
      for (final b in bytes) b < 0x80 ? b : _cp1256[b - 0x80],
    ]),
    'iso-8859-6' ||
    'iso8859-6' => String.fromCharCodes([for (final b in bytes) _iso88596(b)]),
    'iso-8859-1' ||
    'latin1' ||
    'windows-1252' ||
    'cp1252' => latin1.decode(bytes, allowInvalid: true),
    _ => utf8.decode(bytes, allowMalformed: true),
  };
}

final _charsetParam = RegExp(r'''charset\s*=\s*["']?([\w-]+)''');
final _xmlEncoding = RegExp(r'''<\?xml[^>]*encoding\s*=\s*["']([\w-]+)''');

/// ISO-8859-6: ASCII plus Arabic letters at 0xC1–0xF2 (U+0621–U+0652).
int _iso88596(int b) {
  if (b < 0xA0) return b;
  if (b >= 0xC1 && b <= 0xF2) return b - 0xC1 + 0x0621;
  return switch (b) {
    0xA0 => 0x00A0,
    0xA4 => 0x00A4,
    0xAC => 0x060C,
    0xAD => 0x00AD,
    0xBB => 0x061B,
    0xBF => 0x061F,
    _ => 0xFFFD,
  };
}

